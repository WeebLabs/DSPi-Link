#!/usr/bin/env python3
"""Embeds the built web pages in the firmware (bridge spec 10.5).

Reads every file of js/apps/web/dist, gzips it, and writes one C source with
the bytes, each file's path, content type and ETag. The web_assets component
runs this at build time; the output lives in the build folder and is never
committed or edited. Hidden files (such as .DS_Store) and source maps are
left out: they would only take flash.

Usage:
    tools/embed_web.py <dist folder> <output .c file>
"""

import gzip
import hashlib
import sys
from pathlib import Path

REPOSITORY_DIR = Path(__file__).resolve().parent.parent.parent.parent

# Built files the bridge does not serve.
SKIPPED_SUFFIXES = {".map"}

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".webmanifest": "application/manifest+json",
    ".woff2": "font/woff2",
}


def c_identifier(index):
    return f"ASSET_{index}"


def c_string(text):
    """A C string literal holding `text`: the quote and backslash escaped, and
    every byte outside printable ASCII written as an octal escape."""
    escaped = []
    for byte in text.encode("utf-8"):
        if byte in (0x22, 0x5C):
            escaped.append("\\" + chr(byte))
        elif 0x20 <= byte < 0x7F:
            escaped.append(chr(byte))
        else:
            escaped.append(f"\\{byte:03o}")
    return '"' + "".join(escaped) + '"'


def comment_safe(text):
    """`text` with anything that could end a C comment taken out."""
    return text.replace("*/", "*_/")


def is_served(path, dist):
    parts = path.relative_to(dist).parts
    return path.is_file() and not any(part.startswith(".") for part in parts) and \
        path.suffix not in SKIPPED_SUFFIXES


def source_name(dist):
    """The dist folder as the generated file names it: relative to the
    repository when inside it, so the output is the same on every machine."""
    try:
        return dist.resolve().relative_to(REPOSITORY_DIR).as_posix()
    except ValueError:
        return dist.name


def render(dist):
    files = sorted(p for p in dist.rglob("*") if is_served(p, dist))
    lines = [
        "/* GENERATED by tools/embed_web.py; do not edit by hand.",
        " *",
        f" * web_assets_data.c - the web pages from {comment_safe(source_name(dist))}.",
        " * Rebuild the web pages and the firmware instead of editing this.",
        " */",
        "",
        '#include "web_assets.h"',
        "",
    ]
    table = []
    for index, path in enumerate(files):
        url = "/" + path.relative_to(dist).as_posix()
        content_type = CONTENT_TYPES.get(path.suffix, "application/octet-stream")
        # mtime=0 keeps the output identical from build to build.
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        etag = '"' + hashlib.sha256(data).hexdigest()[:16] + '"'
        immutable = "true" if url.startswith("/assets/") else "false"

        lines.append(f"/* {comment_safe(url)}: {path.stat().st_size} bytes, {len(data)} gzipped */")
        lines.append(f"static const uint8_t {c_identifier(index)}[] = {{")
        for start in range(0, len(data), 16):
            chunk = ", ".join(f"0x{b:02x}" for b in data[start:start + 16])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
        table.append(
            f"    {{{c_string(url)}, {c_string(content_type)}, {c_identifier(index)}, "
            f"sizeof({c_identifier(index)}), {c_string(etag)}, {immutable}}},"
        )

    lines.append("const web_asset_t WEB_ASSETS[] = {")
    lines += table
    lines.append("};")
    lines.append("")
    lines.append(f"const size_t WEB_ASSET_COUNT = {len(files)};")
    lines.append("")
    return "\n".join(lines), files


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    dist, output = Path(sys.argv[1]), Path(sys.argv[2])
    if not (dist / "index.html").exists():
        print(f"{dist}/index.html is missing: build the web pages with "
              "'cd js && npm ci && npm run build'", file=sys.stderr)
        return 1
    text, files = render(dist)
    output.write_text(text)
    print(f"Embedded {len(files)} web files in {output.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
