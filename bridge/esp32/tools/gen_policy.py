#!/usr/bin/env python3
"""Generates the bridge's authorization table from policy/commands.json.

Link spec 9.3: every hub embeds the shared policy table rather than
transcribing it by hand. This script turns the JSON into
components/link_policy/link_policy_table.c, which is committed so the build
needs no Python step and reviewers can read the result.

It also checks the table against the firmware's command registry, copied
into policy/firmware/dspi_commands.json: every command and direction the
firmware has must be classed, and nothing else.

Usage:
    tools/gen_policy.py           write the table
    tools/gen_policy.py --check   fail if the table is out of date, or the
                                  JSON does not match the registry (CI)
"""

import json
import sys
from pathlib import Path

BRIDGE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = BRIDGE_DIR.parent.parent
POLICY_JSON = REPO_DIR / "policy" / "commands.json"
REGISTRY_JSON = REPO_DIR / "policy" / "firmware" / "dspi_commands.json"
OUTPUT_C = BRIDGE_DIR / "components" / "link_policy" / "link_policy_table.c"

CLASS_NAMES = {"read": "LINK_CLASS_READ", "control": "LINK_CLASS_CONTROL", "config": "LINK_CLASS_CONFIG"}


def registry_directions(registry):
    """{command ID: (name, set of directions)} from the firmware registry."""
    commands = {}
    for page in registry["pages"]:
        for command in page["commands"]:
            directions = {d for d in ("get", "set") if command[d]}
            commands[command["id"]] = (f"{page['mnemonic']}.{command['name']}", directions)
    return commands


def problems(policy, registry):
    """Every way the policy table and the registry disagree, as sentences."""
    found = []
    expected = registry_directions(registry)
    seen = set()
    for row in policy["commands"]:
        command_id, name, classes = row["id"], row["name"], row["classes"]
        if command_id in seen:
            found.append(f"{name}: ID 0x{command_id:04X} is listed twice")
        seen.add(command_id)
        if command_id not in expected:
            found.append(f"{name}: ID 0x{command_id:04X} is not in the firmware registry")
            continue
        registry_name, directions = expected[command_id]
        if name != registry_name:
            found.append(f"0x{command_id:04X}: named {name}, the registry says {registry_name}")
        if set(classes) != directions:
            found.append(f"{name}: classes {sorted(classes)}, the registry has {sorted(directions)}")
        for direction, class_ in classes.items():
            if class_ not in CLASS_NAMES:
                found.append(f"{name}: unknown class {class_!r} for {direction}")
        if classes.get("get", "read") != "read":
            found.append(f"{name}: every GET is read (Link spec 6.3)")
    for command_id, (name, _) in sorted(expected.items()):
        if command_id not in seen:
            found.append(f"{name}: in the firmware registry but not classed")
    return found


def render(policy):
    rows = sorted(policy["commands"], key=lambda row: row["id"])
    lines = [
        "/* GENERATED by tools/gen_policy.py; do not edit by hand.",
        " *",
        " * link_policy_table.c - the authorization table from policy/commands.json",
        f" * (spec {policy['spec_version']}). Run the script again after changing the JSON.",
        " *",
        " * One row per firmware command, sorted by command ID: {ID, SET class, GET",
        " * class}. A direction the command lacks is LINK_CLASS_CONFIG, and so is an",
        " * ID the table does not list, so an unknown command is admin-only (Link",
        " * spec 9.3 and 10.7).",
        " */",
        "",
        '#include "link_policy.h"',
        '#include "link_policy_table.h"',
        "",
        f'const char LINK_POLICY_SPEC_VERSION[] = "{policy["spec_version"]}";',
        "",
        "const link_policy_row_t LINK_POLICY_TABLE[] = {",
    ]
    for row in rows:
        set_class = CLASS_NAMES[row["classes"].get("set", "config")]
        get_class = CLASS_NAMES[row["classes"].get("get", "config")]
        lines.append(f"    {{0x{row['id']:04X}, {set_class}, {get_class}}}, /* {row['name']} */")
    lines += [
        "};",
        "",
        "const size_t LINK_POLICY_TABLE_ROWS = sizeof(LINK_POLICY_TABLE) / sizeof(LINK_POLICY_TABLE[0]);",
        "",
    ]
    return "\n".join(lines)


def main():
    policy = json.loads(POLICY_JSON.read_text())
    registry = json.loads(REGISTRY_JSON.read_text())
    found = problems(policy, registry)
    for problem in found:
        print(f"policy/commands.json: {problem}", file=sys.stderr)
    if found:
        return 1
    text = render(policy)
    if "--check" in sys.argv:
        if not OUTPUT_C.exists() or OUTPUT_C.read_text() != text:
            print(f"{OUTPUT_C.relative_to(BRIDGE_DIR)} is out of date: run tools/gen_policy.py",
                  file=sys.stderr)
            return 1
        print("link_policy_table.c is up to date and matches the firmware registry")
        return 0
    OUTPUT_C.write_text(text)
    print(f"Wrote {OUTPUT_C.relative_to(BRIDGE_DIR)} ({len(policy['commands'])} commands)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
