#!/usr/bin/env python3
"""Generates the bridge's authorization table from policy/commands.json.

Link spec 9.3: every hub embeds the shared policy table rather than
transcribing it by hand. This script turns the JSON into
components/link_policy/link_policy_table.c, which is committed so the build
needs no Python step and reviewers can read the result.

Usage:
    tools/gen_policy.py           write the table
    tools/gen_policy.py --check   fail if the committed table is out of date (CI)
"""

import json
import sys
from pathlib import Path

BRIDGE_DIR = Path(__file__).resolve().parent.parent
POLICY_JSON = BRIDGE_DIR.parent.parent / "policy" / "commands.json"
OUTPUT_C = BRIDGE_DIR / "components" / "link_policy" / "link_policy_table.c"

CLASS_NAMES = {"read": "LINK_CLASS_READ", "control": "LINK_CLASS_CONTROL", "config": "LINK_CLASS_CONFIG"}


def class_for(command, direction):
    """The class of one direction: `classes` decides where present (spec 9.3);
    a direction the command does not list is config, the strictest."""
    if direction not in command["dirs"]:
        return "config"
    return command.get("classes", {}).get(direction, command["class"])


def render(policy):
    lines = [
        "/*",
        " * link_policy_table.c - GENERATED by tools/gen_policy.py from",
        f" * policy/commands.json (spec {policy['spec_version']}). Do not edit by hand; run the",
        " * script after changing the JSON.",
        " *",
        " * One row per bRequest: {SET class, GET class}. Rows the JSON does not",
        " * list are left out, and C initialises them to LINK_CLASS_CONFIG (zero),",
        " * so an unknown command is admin-only (Link spec 9.3 and 10.7).",
        " */",
        "",
        '#include "link_policy.h"',
        "",
        f'const char LINK_POLICY_SPEC_VERSION[] = "{policy["spec_version"]}";',
        "",
        "const uint8_t LINK_POLICY_TABLE[256][2] = {",
    ]
    for command in sorted(policy["commands"], key=lambda c: c["code"]):
        set_class = CLASS_NAMES[class_for(command, "set")]
        get_class = CLASS_NAMES[class_for(command, "get")]
        lines.append(
            f"    [0x{command['code']:02X}] = {{{set_class}, {get_class}}}, /* {command['name']} */"
        )
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    policy = json.loads(POLICY_JSON.read_text())
    text = render(policy)
    if "--check" in sys.argv:
        if not OUTPUT_C.exists() or OUTPUT_C.read_text() != text:
            print(f"{OUTPUT_C.relative_to(BRIDGE_DIR)} is out of date: run tools/gen_policy.py")
            return 1
        print("link_policy_table.c is up to date")
        return 0
    OUTPUT_C.write_text(text)
    print(f"Wrote {OUTPUT_C.relative_to(BRIDGE_DIR)} ({len(policy['commands'])} commands)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
